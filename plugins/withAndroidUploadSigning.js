const { withAppBuildGradle } = require('@expo/config-plugins');

const MARKER = '// @generated by withAndroidUploadSigning';

const SIGNING_CONFIG = `${MARKER}
def myTurnUploadKeyDirectory = new File(System.getProperty("user.home"), ".android-upload-keys")
def myTurnUploadPropertiesFile = new File(myTurnUploadKeyDirectory, "signing.properties")
def myTurnUploadProperties = new Properties()

if (myTurnUploadPropertiesFile.exists()) {
    myTurnUploadPropertiesFile.withInputStream {
        myTurnUploadProperties.load(it)
    }
}

def myTurnSigningValue = { String environmentName, String propertyName, String defaultValue = null ->
    System.getenv(environmentName) ?: myTurnUploadProperties.getProperty(propertyName) ?: defaultValue
}

def myTurnUploadStorePath = myTurnSigningValue(
    "MYTURN_UPLOAD_STORE_FILE",
    "storeFile",
    "myturn-upload.p12"
)
def myTurnUploadStoreFile = new File(myTurnUploadStorePath)
if (!myTurnUploadStoreFile.isAbsolute()) {
    myTurnUploadStoreFile = new File(myTurnUploadKeyDirectory, myTurnUploadStorePath)
}

def myTurnUploadStorePassword = myTurnSigningValue(
    "MYTURN_UPLOAD_STORE_PASSWORD",
    "storePassword"
)
if (!myTurnUploadStoreFile.isFile()) {
    throw new GradleException(
        "Android upload keystore not found: " + myTurnUploadStoreFile
    )
}
if (!myTurnUploadStorePassword) {
    throw new GradleException(
        "Missing Android upload keystore password. Set storePassword in " +
        myTurnUploadPropertiesFile +
        " or set MYTURN_UPLOAD_STORE_PASSWORD."
    )
}

def myTurnUploadKeyAlias = myTurnSigningValue(
    "MYTURN_UPLOAD_KEY_ALIAS",
    "keyAlias"
)

if (!myTurnUploadKeyAlias) {
    def myTurnUploadKeyStore = java.security.KeyStore.getInstance("PKCS12")
    try {
        myTurnUploadStoreFile.withInputStream {
            myTurnUploadKeyStore.load(
                it,
                myTurnUploadStorePassword.toCharArray()
            )
        }
    } catch (Exception error) {
        throw new GradleException(
            "Could not unlock Android upload keystore " +
            myTurnUploadStoreFile +
            ". Check storePassword.",
            error
        )
    }

    def myTurnUploadAliases = Collections.list(
        myTurnUploadKeyStore.aliases()
    ).findAll {
        myTurnUploadKeyStore.isKeyEntry(it)
    }

    if (myTurnUploadAliases.size() != 1) {
        throw new GradleException(
            "Expected one private-key alias in " +
            myTurnUploadStoreFile +
            " but found " +
            myTurnUploadAliases.size() +
            ". Set keyAlias in " +
            myTurnUploadPropertiesFile +
            "."
        )
    }

    myTurnUploadKeyAlias = myTurnUploadAliases.first()
}

def myTurnUploadKeyPassword = myTurnSigningValue(
    "MYTURN_UPLOAD_KEY_PASSWORD",
    "keyPassword",
    myTurnUploadStorePassword
)

def myTurnUploadPasswordSource = System.getenv(
    "MYTURN_UPLOAD_STORE_PASSWORD"
) ? "MYTURN_UPLOAD_STORE_PASSWORD environment variable" :
    myTurnUploadPropertiesFile.toString()

println(
    "[MyTurn Signing] Signing production Android build with " +
    myTurnUploadStoreFile +
    " (PKCS12), alias " +
    myTurnUploadKeyAlias +
    ", password ****** from " +
    myTurnUploadPasswordSource
)
`;

function addSigningConfig(contents) {
  const debugConfig = `    signingConfigs {
        debug {`;

  if (!contents.includes(debugConfig)) {
    throw new Error(
      'Could not find the Android debug signing configuration generated by Expo.',
    );
  }

  return contents.replace(
    debugConfig,
    `    signingConfigs {
        release {
            storeFile myTurnUploadStoreFile
            storePassword myTurnUploadStorePassword
            keyAlias myTurnUploadKeyAlias
            keyPassword myTurnUploadKeyPassword
            storeType "PKCS12"
        }
        debug {`,
  );
}

function useReleaseSigningConfig(contents) {
  const debugReleaseSigning = `        release {
            // Caution! In production, you need to generate your own keystore file.
            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig signingConfigs.debug`;

  if (!contents.includes(debugReleaseSigning)) {
    throw new Error(
      'Could not find the debug-signed Android release configuration generated by Expo.',
    );
  }

  return contents.replace(
    debugReleaseSigning,
    `        release {
            signingConfig signingConfigs.release`,
  );
}

module.exports = function withAndroidUploadSigning(config) {
  if (
    process.env.APP_ENV !== 'production' ||
    process.env.LOAD_LOCAL_ENV !== 'true'
  ) {
    return config;
  }

  return withAppBuildGradle(config, (config) => {
    if (config.modResults.language !== 'groovy') {
      throw new Error(
        'Android upload signing currently requires a Groovy app/build.gradle.',
      );
    }

    let contents = config.modResults.contents;
    if (!contents.includes(MARKER)) {
      contents = contents.replace(
        'android {',
        `${SIGNING_CONFIG}

android {`,
      );
      contents = addSigningConfig(contents);
      contents = useReleaseSigningConfig(contents);
    }

    config.modResults.contents = contents;
    return config;
  });
};
