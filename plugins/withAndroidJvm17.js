const { withProjectBuildGradle } = require("@expo/config-plugins");

const MARKER = "// @generated by withAndroidJvm17";

const JVM_CONFIGURATION = `
${MARKER}
gradle.projectsEvaluated {
    subprojects { subproject ->
        subproject.tasks.withType(JavaCompile).configureEach { task ->
            task.sourceCompatibility = JavaVersion.VERSION_17.toString()
            task.targetCompatibility = JavaVersion.VERSION_17.toString()

            if (task.options.hasProperty("release")) {
                task.options.release.set(17)
            }
        }

        subproject.tasks.withType(
            org.jetbrains.kotlin.gradle.tasks.KotlinJvmCompile
        ).configureEach { task ->
            task.compilerOptions {
                jvmTarget.set(
                    org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17
                )
            }
        }
    }
}
`;

module.exports = function withAndroidJvm17(config) {
  return withProjectBuildGradle(config, (config) => {
    if (!config.modResults.contents.includes(MARKER)) {
      config.modResults.contents += JVM_CONFIGURATION;
    }

    return config;
  });
};